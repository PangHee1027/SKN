# 계산 방식은 나랑 비슷한데 내장 함수 사용법, 초기값 설정 등에서 차이가 좀 난듯
def solution(a,b):
    month = [31, 29, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]
    day = ['FRI', 'SAT', 'SUN', 'MON', 'TUE', 'WED', 'THU']
    # a - 1 월 까지 각 달의 일수의 합을 구함 (sum(month[:a-1]))
    # 거기에 b를 더함 근데 0부터 시작이니까 -1을 함
    # 그걸 7로 나누고 day의 인덱싱을 함
    return day[(sum(month[:a-1])+b-1)%7]