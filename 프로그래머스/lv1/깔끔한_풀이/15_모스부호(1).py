# 쉬운 문제라서 큰 틀에선 다를바 없음
def solution(letter):
    morse = {
        '.-':'a','-...':'b','-.-.':'c','-..':'d','.':'e','..-.':'f',
        '--.':'g','....':'h','..':'i','.---':'j','-.-':'k','.-..':'l',
        '--':'m','-.':'n','---':'o','.--.':'p','--.-':'q','.-.':'r',
        '...':'s','-':'t','..-':'u','...-':'v','.--':'w','-..-':'x',
        '-.--':'y','--..':'z'
    }
    # 다만 이 부분에서 코드를 간결화 하는 게 아직 난 부족하다고 생각이 듬
    return ''.join([morse[i] for i in letter.split(' ')])