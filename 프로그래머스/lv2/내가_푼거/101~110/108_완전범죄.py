def solution(info, n, m):
    # current_states 딕셔너리 정의:
    # 키(Key)는 A도둑의 누적 흔적(a), 값(Value)은 그 때 B도둑이 남긴 최소 흔적(b)을 저장합니다.
    # 시작 시점에는 두 도둑 모두 흔적이 0이므로 {0: 0}으로 초기화합니다.
    current_states = {0: 0}
    
    # 주어진 물건 정보(info)를 하나씩 순회하며 탐색을 진행합니다.
    for da, db in info:
        # 이번 물건을 처리한 결과(다음 단계의 유효한 상태들)를 저장할 임시 딕셔너리
        next_states = {}
        
        # 현재 단계에서 도달 가능한 모든 (A의 흔적 a, B의 흔적 b) 상태를 순회합니다.
        for a, b in current_states.items():
            
            # -------------------------------------------------------------
            # 경우 1: A도둑이 현재 물건을 훔치는 경우
            # -------------------------------------------------------------
            # B의 흔적(b)은 그대로 유지되고, A의 흔적만 현재 흔적 a에 이번 물건의 흔적 da를 더한 만큼 늘어납니다.
            next_a = a + da
            
            # A도둑의 누적 흔적이 경찰에 붙잡히는 기준(n) 미만일 때만 유효한 상태입니다.
            if next_a < n:  
                # 만약 아직 해당 A 흔적(next_a)에 도달한 적이 없거나, 
                # 기존에 저장된 B의 흔적보다 현재 탐색한 B의 흔적(b)이 더 작다면 최솟값으로 갱신합니다.
                if next_a not in next_states or next_states[next_a] > b:
                    next_states[next_a] = b
                    
            # -------------------------------------------------------------
            # 경우 2: B도둑이 현재 물건을 훔치는 경우
            # -------------------------------------------------------------
            # A의 흔적(a)은 그대로 유지되고, B의 흔적만 현재 흔적 b에 이번 물건의 흔적 db를 더한 만큼 늘어납니다.
            next_b = b + db
            
            # B도둑의 누적 흔적이 경찰에 붙잡히는 기준(m) 미만일 때만 유효한 상태입니다.
            if next_b < m:  
                # 만약 해당 A 흔적(a)에 대해 아직 저장된 B의 흔적 상태가 없거나, 
                # 기존에 저장된 B의 흔적보다 새로 계산된 B의 흔적(next_b)이 더 작다면 최솟값으로 갱신합니다.
                if a not in next_states or next_states[a] > next_b:
                    next_states[a] = next_b
                    
        # 다음 물건 탐색을 위해 현재 상태 테이블을 이번 단계의 결과(next_states)로 교체합니다.
        current_states = next_states
        
        # 만약 도중에 모든 경로가 경찰에 붙잡히거나 제한을 초과하여 유효한 상태가 하나도 없다면,
        # 더 이상 진행할 수 없으므로 즉시 -1을 반환합니다.
        if not current_states:
            return -1
            
    # 모든 물건을 다 훔친 후, 살아남은 상태들(current_states) 중 
    # A도둑이 남긴 흔적(딕셔너리의 키값들) 중에서 가장 작은 값(min)을 찾아 반환합니다.
    # 만약 비어있다면 -1을 반환합니다.
    return min(current_states.keys()) if current_states else -1