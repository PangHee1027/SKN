def solution(numbers):
    answer = []
    
    for x in numbers:
        # [Case 1] x가 짝수인 경우 (이진수의 최하위 비트가 '0')
        # 예: 2 (10_2) -> 3 (11_2), 6 (110_2) -> 7 (111_2)
        # 맨 오른쪽 0 비트만 1로 바꾸면(+1) x보다 크면서 비트가 1개만 다른 최솟값이 됩니다.
        if x % 2 == 0:
            answer.append(x + 1)
            
        # [Case 2] x가 홀수인 경우 (이진수가 '...011...1' 형태)
        # 가장 작은 수를 만들려면 가장 하위의 '0'을 '1'로 바꾸고, 
        # 그 바로 오른쪽 비트('1')를 '0'으로 바꿔야 비트가 2개 변경됩니다.
        # 예: 7 (0111_2) -> 11 (1011_2)
        else:
            # 1. 가장 하위에 있는 '0'의 자릿값(2^c) 추출하기
            #    - x + 1 : 최하위 연속된 1을 0으로 바꾸고, 가장 가까운 0을 1로 올림 처리 (예: 7(0111_2) + 1 = 8(1000_2))
            #    - ~x    : x의 모든 비트를 반전시킴 (예: ~7 = ...1000_2)
            #    - ~x & (x + 1) : 두 값을 AND 연산하여 가장 하위 0의 자릿값만 남김 (예: 8)
            lowest_zero = ~x & (x + 1)
            
            # 2. 비트 변경을 수식으로 적용하기
            #    - 하위 0을 1로 바꿈: + lowest_zero (+2^c)
            #    - 그 우측 1을 0으로 바꿈: - (lowest_zero >> 1) (-2^(c-1))
            #    - 수식 정리: x + 2^c - 2^(c-1) = x + 2^(c-1)
            #    따라서 lowest_zero를 오른쪽으로 1비트 시프트(>> 1)한 값을 x에 더해주면 완성됩니다.
            #    (예: 7 + (8 >> 1) = 7 + 4 = 11)
            answer.append(x + (lowest_zero >> 1))
            
    return answer