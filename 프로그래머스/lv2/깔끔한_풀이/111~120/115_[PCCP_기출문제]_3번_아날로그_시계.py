def count_alarms(time):
  """0초(0시 0분 0초)부터 특정 시간(time 초)까지

  누적해서 알람이 울린 총 횟수를 계산하는 함수입니다.
  """
  if time < 0:
    return 0

  # [1] 초침과 분침이 겹치는 횟수 계산
  # - 초침의 속도: 360도 / 60초 = 6도/초
  # - 분침의 속도: 360도 / 3600초(60분) = 0.1도/초
  # - 초침이 분침을 따라잡는 상대 속도: 6 - 0.1 = 5.9도/초 (59/10도/초)
  # - 360도를 한 바퀴 따라잡는 주기: 360 / (59/10) = 3600 / 59초
  # - 0초 시점(시작점)에 기본으로 1번 겹친다고 가정하므로 (+1)을 더해줍니다.
  minute_matches = (59 * time) // 3600 + 1

  # [2] 초침과 시침이 겹치는 횟수 계산
  # - 초침의 속도: 6도/초
  # - 시침의 속도: 360도 / 43200초(12시간) = 1/120도/초
  # - 초침이 시침을 따라잡는 상대 속도: 6 - 1/120 = 719/120도/초
  # - 360도를 한 바퀴 따라잡는 주기: 360 / (719/120) = 43200 / 719초
  # - 마찬가지로 0초 시점의 기본 1회를 포함하기 위해 (+1)을 더해줍니다.
  hour_matches = (719 * time) // 43200 + 1

  # [3] 삼중 겹침(초침, 분침, 시침이 모두 동시에 겹치는 순간) 보정
  # - 0초(0시 정각)에는 초-분 겹침과 초-시 겹침이 동시에 일어나므로 1번 중복 카운트됨 (-1)
  # - 12시 정각(43200초)에도 세 바늘이 동시에 겹치므로 총 2번 중복 카운트됨 (-2)
  overlap = 1
  if time >= 43200:
    overlap = 2

  # 초-분 겹치 횟수 + 초-시 겹침 횟수 - 삼중 겹침 중복 제거
  return minute_matches + hour_matches - overlap


def solution(h1, m1, s1, h2, m2, s2):
  # 입력받은 시작 시각과 종료 시각을 0시 0분 0초 기준 총 '초(second)' 단위로 환산합니다.
  start_time = h1 * 3600 + m1 * 60 + s1
  stop_time = h2 * 3600 + m2 * 60 + s2

  # [4] 시작 시각(start_time) 그 자체에 정확히 알람이 울렸는지 확인
  # (초침과 분침의 각도 차가 0이거나, 초침과 시침의 각도 차가 0인 순간인지 체크)
  start_is_alarm = 0
  if (59 * start_time) % 3600 == 0 or (719 * start_time) % 43200 == 0:
    start_is_alarm = 1

  # [5] 구간 내 알람 횟수 계산 공식
  # 전체 구간 횟수 = (0초부터 stop_time까지의 누적 횟수) - (0초부터 start_time까지의 누적 횟수) + (시작 시각 자체 알람 여부)
  # ※ 뺄 때 start_time 시각의 누적 횟수를 통째로 빼버리므로, start_time 정각에 울린 알람이 포함되었다면
  #    마지막에 `start_is_alarm`을 더해서 보정해 줍니다.
  return count_alarms(stop_time) - count_alarms(start_time) + start_is_alarm