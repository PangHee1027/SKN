def solution(info, n, m):
    # dp[b] 배열 정의:
    # B도둑이 누적 흔적을 b만큼 남겼을 때, 
    # A도둑이 남길 수 있는 최소 흔적의 개수를 저장합니다.
    # 초기에는 어떤 상태도 도달할 수 없으므로 무한대(float('inf'))로 초기화합니다.
    # B의 흔적은 m 미만이어야 하므로 크기를 m으로 설정합니다.
    dp = [float('inf')] * m
    
    # 초기 상태 설정:
    # 물건을 하나도 훔치기 전(시작점)에는 
    # A도 0개, B도 0개의 흔적을 가지므로 dp[0] = 0으로 시작합니다.
    dp[0] = 0  
    
    # 각 물건을 순회하며 두 도둑이 훔쳤을 때의 상태를 차례대로 갱신합니다.
    for da, db in info:
        # 이번 물건을 처리한 결과를 임시로 저장할 새로운 DP 테이블
        next_dp = [float('inf')] * m
        
        # 현재 가능한 B의 흔적(b) 상태들을 순회합니다.
        for b in range(m):
            # 만약 현재 B의 흔적 b에 도달할 수 없는 상태라면(inf라면) 계산할 필요가 없으므로 건너뜁니다.
            if dp[b] == float('inf'):
                continue
            
            # -------------------------------------------------------------
            # 경우 1: A도둑이 현재 물건을 훔치는 경우
            # -------------------------------------------------------------
            # B의 흔적(b)은 그대로 유지되고, A의 흔적만 
            # (현재 B 흔적 b일 때의 A 최소 흔적인 dp[b]) + (이번 물건의 A 흔적 da) 만큼 늘어납니다.
            next_a = dp[b] + da
            
            # A도둑이 경찰에 붙잡히는 기준(n 이상) 미만일 때만 유효한 상태입니다.
            if next_a < n:
                # 동일한 B의 흔적(b) 상태에 대해 더 작은 A의 흔적 값으로 갱신합니다.
                next_dp[b] = min(next_dp[b], next_a)
            
            # -------------------------------------------------------------
            # 경우 2: B도둑이 현재 물건을 훔치는 경우
            # -------------------------------------------------------------
            # A의 흔적(dp[b])은 그대로 유지되고, B의 흔적만 
            # (현재 B의 흔적 b) + (이번 물건의 B 흔적 db) 만큼 늘어납니다.
            next_b = b + db
            
            # B도둑이 경찰에 붙잡히는 기준(m 이상) 미만일 때만 유효한 상태입니다.
            if next_b < m:
                # 새로 만들어진 B의 흔적(next_b) 위치에 
                # 기존 A의 흔적 값(dp[b]) 중 더 작은 값을 저장합니다.
                next_dp[next_b] = min(next_dp[next_b], dp[b])
                
        # 다음 물건 탐색을 위해 현재 단계의 DP 테이블을 갱신합니다.
        dp = next_dp
        
    # 모든 물건을 다 훔친 후, 
    # 가능한 모든 B의 흔적(0 ~ m-1) 상태에서 A가 기록한 최소 흔적들의 최솟값을 찾습니다.
    min_a = min(dp)
    
    # 만약 최솟값이 여전히 무한대라면, 어떤 방법으로도 경찰에 붙잡히지 않고 
    # 모든 물건을 훔칠 수 없다는 뜻이므로 -1을 반환합니다.
    return min_a if min_a != float('inf') else -1