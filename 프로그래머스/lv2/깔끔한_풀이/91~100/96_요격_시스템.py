def solution(targets):
    # 1. 그리디(Greedy) 알고리즘 적용: 미사일들을 '끝점(e)'을 기준으로 오름차순 정렬합니다.
    #    - 가장 빨리 끝나는 미사일을 먼저 처리해야, 그 미사일의 끝자락에 요격 미사일을 쏘았을 때
    #      최대한 많은 다음 미사일들을 함께 방어(오버랩)할 수 있습니다.
    targets.sort(key=lambda x: x[1])
    
    answer = 0       # 필요한 총 요격 미사일의 개수
    last_end = -1    # 직전에 발사한 요격 미사일의 x 좌표 (초기값은 유효 범위 밖인 -1로 설정)
    
    # 2. 정렬된 미사일들을 하나씩 확인하며 요격 여부를 판단합니다.
    for s, e in targets:
        # 현재 미사일의 시작점(s)이 직전 요격 위치(last_end)보다 크거나 같다면,
        # 기존 요격 미사일의 방어 범위를 벗어났으므로 새로운 요격 미사일이 반드시 필요합니다.
        # ※ 참고: 문제에서 개구간(s, e)을 제시했으므로 s == last_end인 경우도 
        #   경계선에 걸쳐있어 요격이 불가능하므로 크거나 같음(>=) 조건을 사용합니다.
        if s >= last_end:
            answer += 1
            
            # 새로운 요격 미사일을 현재 미사일의 '끝점(e)' 바로 직전에 설치합니다.
            # 최대한 오른쪽(끝점)에 설치해야 뒤에 올 미사일들과 겹칠 확률이 높아집니다.
            last_end = e  
            
    return answer